import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const repository = new URL('../', import.meta.url);
const directory = new URL('packages/scene-model/assets/fonts/roboto-condensed/', repository);
const target = new URL('packages/scene-model/src/generatedRecipeFonts.ts', repository);
const upstreamCommit = '69d0549e8fc7ad72e1531734c81237be401ec4fd';
const upstream = `https://github.com/google/fonts/blob/${upstreamCommit}/ofl/robotocondensed`;
const expectedHash = 'dace262afcee68a5276f200d8026c57221735c0118ab5fda8c2c0d3dc409a8d0';
const [font, licenseText] = await Promise.all([
  readFile(new URL('RobotoCondensed.ttf', directory)),
  readFile(new URL('OFL.txt', directory), 'utf8'),
]);
const hash = createHash('sha256').update(font).digest('hex');
if (hash !== expectedHash || font.byteLength !== 371616)
  throw new Error('The bundled Roboto Condensed font does not match its pinned upstream bytes.');
if (!font.subarray(0, 4).equals(Buffer.from([0, 1, 0, 0])))
  throw new Error('The bundled Roboto Condensed resource is not a TrueType font.');
if (!licenseText.trim())
  throw new Error('The bundled font requires its complete upstream license.');

const asset = {
  id: `asset-recipe-roboto-condensed-${hash.slice(0, 12)}`,
  name: 'Roboto Condensed Variable',
  kind: 'font',
  dataUri: `data:font/ttf;base64,${font.toString('base64')}`,
  mimeType: 'font/ttf',
  originalFileName: 'RobotoCondensed[wght].ttf',
  byteSize: font.byteLength,
  packagePath: `assets/fonts/roboto-condensed-${hash.slice(0, 12)}.ttf`,
  fontFamily: 'Roboto Condensed',
  fontWeight: '100 900',
  fontStyle: 'normal',
  licenseName: 'SIL Open Font License 1.1',
  licenseUrl: `${upstream}/OFL.txt`,
  licenseText,
};
const source = `// Generated by scripts/generateRecipeFonts.mjs. Do not edit.
// Font: ${upstream}/RobotoCondensed%5Bwght%5D.ttf
// License: ${upstream}/OFL.txt
// SHA-256: ${hash}
import type { Asset } from './types';

/** Recipe-only source data; unused authoring helpers and this literal are tree-shaken from playout. */
export const RECIPE_ROBOTO_CONDENSED: Readonly<Asset> = /* @__PURE__ */ Object.freeze(${JSON.stringify(asset)});
`;
const generated = await format(source, {
  ...(await resolveConfig(fileURLToPath(target))),
  parser: 'typescript',
});
if (process.argv.includes('--check')) {
  const existing = await readFile(target, 'utf8').catch(() => '');
  if (existing !== generated)
    throw new Error('Bundled recipe fonts are stale. Run npm run fonts:generate.');
  console.log(`Recipe font source verified: Roboto Condensed (${font.byteLength} bytes, ${hash}).`);
} else {
  await writeFile(target, generated);
  console.log(`Generated portable recipe font source: ${fileURLToPath(target)}.`);
}
