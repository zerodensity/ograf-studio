import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import ts from 'typescript';

const root = new URL('../packages/codegen/src/', import.meta.url);
const runtime = await readFile(new URL('offlinePreviewRuntime.js', root), 'utf8');
const nodosRuntime = await readFile(new URL('nodosInputRuntime.js', root), 'utf8');
const style = await readFile(new URL('offlinePreview.css', root), 'utf8');
const scheduler = await readFile(new URL('offlinePreviewScheduler.js', root), 'utf8');
const laneData = await readFile(new URL('offlinePreviewLaneData.js', root), 'utf8');
const fps = await readFile(
  new URL('../packages/ui-kit/src/previewFps.js', import.meta.url),
  'utf8',
);
const controlsSource = await readFile(
  new URL('../apps/editor/src/panels/previewControlsInteraction.ts', import.meta.url),
  'utf8',
);
const controlsRuntime = ts
  .transpileModule(controlsSource, {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
  })
  .outputText.replace(/^import \{ isPreviewPresented \} from ['"][^'"]+['"];\r?\n/m, '')
  .replace(/^export /gm, '');
if (/^\s*import\s/m.test(controlsRuntime))
  throw new Error('Studio preview control interactions have an unbundled dependency.');
const controlsStyle = await readFile(
  new URL('../apps/editor/src/panels/PreviewControlsInteraction.css', import.meta.url),
  'utf8',
);
const presentationAdapter = `function isPreviewPresented(viewport) { return viewport?.hasAttribute('data-preview-overlay') === true; }`;
// Keep the standalone controls' typography identical to Studio without a network dependency.
const editorMain = await readFile(new URL('../apps/editor/src/main.tsx', import.meta.url), 'utf8');
const nunitoRoot = new URL('../node_modules/@fontsource/nunito/', import.meta.url);
const fontLicense = await readFile(new URL('LICENSE', nunitoRoot), 'utf8');
const fontStyles = [];
for (const match of editorMain.matchAll(/import '@fontsource\/nunito\/([a-z0-9-]+\.css)'/g)) {
  const css = await readFile(new URL(match[1], nunitoRoot), 'utf8');
  const fontPath = css.match(/url\(\.\/files\/(nunito-[a-z0-9-]+\.woff2)\)/)?.[1];
  if (!fontPath) throw new Error(`Nunito stylesheet ${match[1]} has no local WOFF2 font.`);
  const bytes = await readFile(new URL(`files/${fontPath}`, nunitoRoot));
  fontStyles.push(
    css.replace(
      /src:[^;]+;/,
      `src: url(data:font/woff2;base64,${bytes.toString('base64')}) format('woff2');`,
    ),
  );
}
if (!fontStyles.length) throw new Error('Studio Nunito font imports were not found.');
const inlineStyle = `/* Nunito font license (embedded with its font files):\n${fontLicense.replace(/\*\//g, '* /')}\n*/\n${fontStyles.join('\n')}\n${style}\n${controlsStyle}`;
const target = new URL('offlinePreviewAssets.ts', root);
const raw = `// Generated by scripts/generateOfflinePreviewAssets.mjs; do not edit.\nexport const OFFLINE_PREVIEW_RUNTIME = ${JSON.stringify(fps.replace(/^export /gm, '') + '\n' + presentationAdapter + '\n' + controlsRuntime + '\n' + scheduler + '\n' + laneData + '\n' + runtime)};\nexport const OFFLINE_PREVIEW_STYLE = ${JSON.stringify(inlineStyle)};\n`;
const content = await format(
  raw + `export const NODOS_INPUT_RUNTIME = ${JSON.stringify(nodosRuntime)};\n`,
  {
    ...(await resolveConfig(fileURLToPath(target))),
    parser: 'typescript',
  },
);
if (process.argv.includes('--check')) {
  const existing = await readFile(target, 'utf8');
  if (existing !== content) throw new Error('Offline preview assets are stale.');
} else await writeFile(target, content);
console.log(
  `Offline preview assets ${process.argv.includes('--check') ? 'verified' : 'generated'}: ${fileURLToPath(target)}`,
);
