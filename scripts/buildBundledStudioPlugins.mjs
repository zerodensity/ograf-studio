import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';
import {
  buildAnimationPluginSnapshot,
  buildChartPluginSnapshot,
  buildShaderPluginSnapshot,
  encodePluginSnapshot,
  repositoryRoot,
} from './pluginPackageSources.mjs';

const publicDirectory = resolve(repositoryRoot, 'apps/editor/public/bundled-plugins');
const generatedPath = resolve(repositoryRoot, 'apps/editor/src/generated/bundledPlugins.ts');
const digest = (bytes) => createHash('sha256').update(bytes).digest('hex');

async function currentBundles() {
  // Read the checked-in sources directly. Release folders, provider overrides and an internet
  // connection must never decide which executable code a Studio distribution trusts.
  const snapshots = await Promise.all([
    buildShaderPluginSnapshot('plugins/zd-news-shaders'),
    buildShaderPluginSnapshot('plugins/zd-news-shaders-2'),
    buildAnimationPluginSnapshot('plugins/broadcast-motion'),
    buildChartPluginSnapshot(),
  ]);
  return Promise.all(
    snapshots.map(async (snapshot) => {
      const bytes = await encodePluginSnapshot(snapshot);
      const bundleSha256 = digest(bytes);
      const { id, kind, name, version } = snapshot.manifest;
      return {
        metadata: {
          id,
          kind,
          version,
          name,
          snapshotSha256: snapshot.sha256,
          bundleSha256,
          filename: `${id}-${version}-${bundleSha256.slice(0, 12)}.ogsplugin.zip`,
          bytes: bytes.byteLength,
        },
        bytes,
      };
    }),
  );
}

async function generatedSource(bundles) {
  return format(
    '// Generated by scripts/buildBundledStudioPlugins.mjs. Do not edit.\n' +
      '// Exact shipped bytes are trusted by the application, never by a downloaded catalog.\n' +
      'export const BUNDLED_STUDIO_PLUGINS_CATALOG_VERSION = 1;\n' +
      `export const BUNDLED_STUDIO_PLUGINS = ${JSON.stringify(bundles.map(({ metadata }) => metadata))} as const;\n`,
    { parser: 'typescript', singleQuote: true, printWidth: 100 },
  );
}

async function writeIfChanged(path, bytes) {
  try {
    if (Buffer.from(await readFile(path)).equals(Buffer.from(bytes))) return;
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, bytes);
}

export async function buildBundledStudioPlugins({ check = false } = {}) {
  const bundles = await currentBundles();
  const source = await generatedSource(bundles);
  const audit =
    JSON.stringify(
      { schemaVersion: 1, plugins: bundles.map(({ metadata }) => metadata) },
      null,
      2,
    ) + '\n';
  if (check) {
    if ((await readFile(generatedPath, 'utf8')) !== source)
      throw new Error('Bundled plugin pins are stale. Run npm run plugins:bundle.');
    if ((await readFile(resolve(publicDirectory, 'catalog.json'), 'utf8')) !== audit)
      throw new Error('Bundled plugin audit catalog is stale. Run npm run plugins:bundle.');
    for (const { metadata } of bundles) {
      const path = resolve(publicDirectory, metadata.filename);
      if (digest(await readFile(path)) !== metadata.bundleSha256)
        throw new Error(`Bundled plugin bytes do not match the application pin: ${metadata.id}`);
    }
  } else {
    for (const { metadata, bytes } of bundles)
      await writeIfChanged(resolve(publicDirectory, metadata.filename), bytes);
    // The JSON copy is an audit/build artifact. Runtime trust uses the compiled TypeScript pins.
    await writeIfChanged(resolve(publicDirectory, 'catalog.json'), audit);
    await writeIfChanged(generatedPath, source);
    const currentNames = new Set(bundles.map(({ metadata }) => metadata.filename));
    for (const filename of await readdir(publicDirectory))
      if (
        /^ograf\.[a-z0-9.-]+-[a-f0-9]{12}\.ogsplugin\.zip$/.test(filename) &&
        !currentNames.has(filename)
      )
        await rm(resolve(publicDirectory, filename));
  }
  return bundles.map(({ metadata }) => metadata);
}

/** A standalone build must include the current source catalog and all four pinned bundles. */
export async function verifyBundledStudioPluginDistribution(directory) {
  const bundles = await currentBundles();
  const catalog = JSON.parse(
    await readFile(resolve(directory, 'bundled-plugins/catalog.json'), 'utf8'),
  );
  const expected = { schemaVersion: 1, plugins: bundles.map(({ metadata }) => metadata) };
  if (JSON.stringify(catalog) !== JSON.stringify(expected))
    throw new Error('Editor distribution has stale bundled plugins. Rebuild the editor first.');
  for (const { metadata } of bundles) {
    const bytes = await readFile(resolve(directory, 'bundled-plugins', metadata.filename));
    if (digest(bytes) !== metadata.bundleSha256)
      throw new Error(`Editor distribution is missing the pinned ${metadata.name} bundle.`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const plugins = await buildBundledStudioPlugins({ check: process.argv.includes('--check') });
  console.log(
    JSON.stringify({ plugins, totalBytes: plugins.reduce((sum, item) => sum + item.bytes, 0) }),
  );
}
